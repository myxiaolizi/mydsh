/** Dictionaries by locale id, exported so tests can compare key sets. */
export const DICTS = Object.freeze({ [ZH]: ZH_DICT, [EN]: EN_DICT });

/** Every key both dictionaries must define. */
export const KEYS = Object.freeze(Object.keys(ZH_DICT));

/**
 * Fill `{name}` placeholders.
 *
 * A missing value is left as the literal placeholder rather than printing
 * `undefined`, because a visible `{n}` in the interface reports the bug without
 * hiding the surrounding sentence.
 */
function interpolate(text, vars) {
  if (vars === undefined || vars === null) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => {
    const value = vars[name];
    return value === undefined || value === null ? match : String(value);
  });
}

/**
 * Build a translate function for one active locale.
 *
 * Lookup falls back from the active locale to English and finally to the key, so an
 * untranslated string still renders something an engineer can trace.
 */
export function makeTranslator(active) {
  const primary = active === ZH ? ZH_DICT : EN_DICT;
  const fallback = active === ZH ? EN_DICT : ZH_DICT;
  const t = (key, vars) => {
    const text = primary[key] ?? fallback[key] ?? key;
    return interpolate(text, vars);
  };
  t.locale = active === ZH ? ZH : EN;
  return t;
}

/**
 * Resolve the translator for the current Client environment.
 *
 * The locale service is the source of truth when it exists: this registers both
 * dictionaries and binds the namespace, which means the shell resolves the active
 * language and re-renders outlets when it changes. Without the service the plugin
 * still works by reading whatever snapshot is available, which keeps older builds
 * and test harnesses usable.
 *
 * Never throws: a broken locale service must not take the settings page down.
 */
export function createTranslator(ctx, onChange) {
  const locale = safeGet(ctx, 'locale');
  if (locale === undefined) {
    const t = makeTranslator(EN);
    return { t, subscribe: () => () => {}, locale: undefined };
  }

  // Registering both dictionaries is what lets the shell switch languages without
  // this plugin being involved in the decision.
  for (const id of [ZH, EN]) {
    try {
      locale.register?.(NS, id, DICTS[id]);
    } catch {
      // A duplicate registration means another instance already added it, which is
      // fine — the bound translator will still resolve against the shared table.
    }
  }

  let bound;
  try {
    bound = locale.bind?.(NS);
  } catch {
    bound = undefined;
  }

  const active = () => {
    try {
      return locale.getLocale?.()?.active;
    } catch {
      return undefined;
    }
  };

  const lookup = (key, vars) => {
    if (typeof bound === 'function') {
      try {
        const text = bound(key, vars);
        // A bound lookup returns the key itself when the namespace lacks it; the
        // local dictionaries are a safer fallback than showing a raw key.
        if (typeof text === 'string' && text !== key) return text;
      } catch {
        // Fall through to the local tables.
      }
    }
    return makeTranslator(active())(key, vars);
  };

  let unsubscribe;
  if (typeof onChange === 'function') {
    try {
      unsubscribe = locale.subscribe?.(() => onChange(active()));
    } catch {
      unsubscribe = undefined;
    }
  }

  return {
    t: lookup,
    locale,
    subscribe: () => () => {
      try {
        unsubscribe?.();
      } catch {
        // Nothing to release.
      }
    },
  };
}

/** Read one Client service without throwing when it is absent. */
function safeGet(ctx, name) {
  try {
    return ctx?.get?.(name);
  } catch {
    return undefined;
  }
}
