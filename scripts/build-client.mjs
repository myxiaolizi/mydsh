#!/usr/bin/env node
/**
 * Client bundle builder for dsh-mydsh.
 *
 * DSH loads a plugin's browser half by executing a script that calls
 * `window.__ModuleLoader__.load({ id, factory })`. The factory receives a
 * `require` bound to the shared platform module table, so React (and other
 * baseline modules) must stay external and be resolved through that require.
 *
 * This script bundles the TypeScript-free source tree into one CommonJS
 * artifact, then wraps it in the loader envelope. `write: false` keeps the
 * intermediate output in memory so no temporary bundle ever reaches disk.
 */
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const entry = resolve(root, 'src/client/index.js');
const outFile = resolve(root, 'lib/client.js');

/** Modules supplied by the DSH page module table; never bundled. */
const PLATFORM_MODULES = ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client'];

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'none',
  external: PLATFORM_MODULES,
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
  loader: { '.svg': 'text', '.png': 'dataurl' },
});

const body = result.outputFiles[0].text;

const banner = `/**
 * dsh-mydsh — 我的DSH
 * Client half of the "我的DSH" bundle for DeepSeek Harness.
 * @license MIT
 * @generated by scripts/build-client.mjs — do not edit by hand
 */
`;

const wrapped = `${banner}window.__ModuleLoader__.load({
  id: 'dsh-mydsh',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  },
});
`;

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, wrapped, 'utf8');

const bytes = Buffer.byteLength(wrapped, 'utf8');
console.log(`client bundle -> ${outFile} (${(bytes / 1024).toFixed(1)} KiB)`);
