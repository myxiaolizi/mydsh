/**
 * Localization for 我的DSH.
 *
 * The shell already ships a locale service, so this plugin registers its own
 * namespace and lets the shell own the choice of language. Two consequences shape
 * the design:
 *
 *  - Nothing here reads the browser or a stored preference. The active language is
 *    whatever DSH resolved, which is what makes the plugin follow the app instead
 *    of fighting it.
 *  - The translator must work even when the service is absent (an older build, or a
 *    test harness), so every call into the service is guarded and the dictionaries
 *    below remain usable on their own.
 *
 * Dictionaries carry identical key sets; `scripts/test-i18n.mjs` enforces that, so
 * a missing translation fails a test instead of showing a raw key to a user.
 */

